def all_codes() -> list[str]:
    """候选池全部代码（去重保序）。"""
    seen: set[str] = set()
    out: list[str] = []
    for items in TECH_UNIVERSE.values():
        for code, _ in items:
            if code not in seen:
                seen.add(code)
                out.append(code)
    return out


def sector_of(code: str) -> str:
    """代码 -> 所属板块名（找不到返回 '其他'）。"""
    for sector, items in TECH_UNIVERSE.items():
        if any(c == code for c, _ in items):
            return sector
    return "其他"


def sectors() -> list[str]:
    """全部板块名。"""
    return list(TECH_UNIVERSE.keys())
