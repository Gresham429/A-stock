def all_codes() -> list[str]:
    """候选池全部代码（去重保序）。"""
    seen: set[str] = set()
    out: list[str] = []
    for subs in MARKET_UNIVERSE.values():
        for items in subs.values():
            for code, _ in items:
                if code not in seen:
                    seen.add(code)
                    out.append(code)
    return out


def primary_sectors() -> list[str]:
    """全部一级板块名。"""
    return list(MARKET_UNIVERSE.keys())


def sub_sectors(primary: str) -> list[str]:
    """某一级板块下的二级细分名（未知一级返回空）。"""
    return list(MARKET_UNIVERSE.get(primary, {}).keys())


def taxonomy() -> dict[str, list[str]]:
    """{一级: [二级...]}，供前端下拉与 /api/config。"""
    return {p: list(subs.keys()) for p, subs in MARKET_UNIVERSE.items()}


def codes_of(focus: str = "") -> list[str]:
    """focus -> 候选代码（去重保序）。

    focus 为一级名 -> 该一级下全部；为二级名 -> 该二级；为空/未知 -> 全池。
    """
    if not focus:
        return all_codes()
    # 一级板块
    if focus in MARKET_UNIVERSE:
        seen: set[str] = set()
        out: list[str] = []
        for items in MARKET_UNIVERSE[focus].values():
            for code, _ in items:
                if code not in seen:
                    seen.add(code)
                    out.append(code)
        return out
    # 二级细分
    for subs in MARKET_UNIVERSE.values():
        if focus in subs:
            return [code for code, _ in subs[focus]]
    return all_codes()


def sector_of(code: str) -> tuple[str, str]:
    """代码 -> (一级, 二级)；找不到返回 ('其他','其他')。"""
    for primary, subs in MARKET_UNIVERSE.items():
        for sub, items in subs.items():
            if any(c == code for c, _ in items):
                return primary, sub
    return "其他", "其他"


def sectors() -> list[str]:
    """向后兼容别名：全部一级板块名。"""
    return primary_sectors()
